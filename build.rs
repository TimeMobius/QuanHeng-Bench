//! Build script: embeds every file under `templates/` into the binary.
//!
//! Registering templates by hand with `include_str!` meant that adding a
//! partial (or a new page) required editing `routes.rs`, and a missing file
//! broke the build with an obscure error. Generating the list here keeps the
//! single-binary deployment while letting templates grow freely.

use std::path::{Path, PathBuf};
use std::{env, fs};

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("templates");
    println!("cargo:rerun-if-changed=templates");

    let mut templates: Vec<(String, PathBuf)> = Vec::new();
    if root.is_dir() {
        collect(&root, &root, &mut templates);
    }
    templates.sort_by(|a, b| a.0.cmp(&b.0));

    let mut source = String::from(
        "// @generated by build.rs — do not edit.\n\
         pub const EMBEDDED_TEMPLATES: &[(&str, &str)] = &[\n",
    );
    for (name, path) in &templates {
        println!("cargo:rerun-if-changed={}", path.display());
        source.push_str(&format!(
            "    ({:?}, include_str!({:?})),\n",
            name,
            path.to_string_lossy()
        ));
    }
    source.push_str("];\n");

    let out_dir = env::var("OUT_DIR").expect("OUT_DIR is always set by cargo");
    fs::write(Path::new(&out_dir).join("embedded_templates.rs"), source)
        .expect("failed to write generated template list");
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(_) => return,
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if path.extension().and_then(|ext| ext.to_str()) == Some("html") {
            let relative = path.strip_prefix(root).unwrap_or(&path);
            out.push((relative.to_string_lossy().replace('\\', "/"), path.clone()));
        }
    }
}
